import { chromium } from '/home/user/qa/node_modules/playwright-core/index.mjs'
const browser = await chromium.launch({ executablePath: '/home/user/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const page = await ctx.newPage()
await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' })
await page.getByRole('navigation').getByRole('button', { name: 'Hadiths', exact: true }).click()
await page.waitForTimeout(1500)
console.log('read-full buttons:', await page.getByText('Read full text').count())
console.log('first card bbox:', JSON.stringify(await page.locator('article').first().boundingBox()))
await page.getByText('Read full text').first().click()
await page.waitForTimeout(400)
await page.locator('article').first().screenshot({ path: '/home/user/qa/shots/10-card-expanded.png' })
// dua view
await page.getByRole('main').getByRole('button', { name: 'Duas & Adhkar', exact: true }).click()
await page.waitForTimeout(1200)
await page.locator('article').nth(1).screenshot({ path: '/home/user/qa/shots/11-dua-card.png' })
await page.getByRole('main').getByRole('button', { name: 'Quranic Duas', exact: true }).click()
await page.waitForTimeout(800)
await page.locator('article').first().screenshot({ path: '/home/user/qa/shots/12-quranic-card.png' })
await page.screenshot({ path: '/home/user/qa/shots/13-quranic-list.png' })
await browser.close()
